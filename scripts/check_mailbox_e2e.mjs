// Browser check for the Mailboxes page (see scripts/mailbox_e2e.py).
import { chromium } from "playwright";
import fs from "node:fs";
const ctxFile = JSON.parse(fs.readFileSync(process.argv[2], "utf8"));
let failed = false;
const check = (label, good) => { console.log((good ? "✓ " : "✗ ") + label); if (!good) failed = true; };
const browser = await chromium.launch();
const context = await browser.newContext({ viewport: { width: 1100, height: 900 } });
await context.addCookies(ctxFile.cookies);
const page = await context.newPage();
const csp = []; page.on("console", m => { if (/Content Security Policy/i.test(m.text())) csp.push(m.text()); });
page.on("dialog", d => { check("no script dialogs", false); d.dismiss(); });
await page.goto("http://localhost:8798/mailboxes");
await page.click(".provider[data-id=proton]");
await page.fill("#mb_name", "Proton"); await page.fill("#mb_email", "me@example.invalid");
await page.fill("#mb_host", "127.0.0.1"); await page.fill("#mb_imap", String(ctxFile.imap)); await page.fill("#mb_smtp", String(ctxFile.smtp));
await page.fill("#mb_user", ctxFile.user); await page.fill("#mb_pass", ctxFile.pw);
await page.click("button:has-text('Connect and test')");
await page.waitForSelector("text=Check connection");
await page.click("text=Check connection");
await page.waitForSelector("text=SMTP: working");
check("connection check reports IMAP and SMTP working", (await page.locator(".alert").allInnerTexts()).join(" | ") === "IMAP: working | SMTP: working");
await page.click("text=Sync now");
await page.waitForSelector("text=3 new");
check("sync adds the three unread emails", (await page.locator(".alert").first().innerText()).startsWith("3 new"));
check("the Mailboxes page shows only the mailbox, not its emails", (await page.locator(".msg").count()) === 0 && !(await page.locator("main, #app").first().innerText()).includes("Quarterly update"));
await page.click("button:has-text('Diagnostics')");
await page.waitForSelector("text=Quarterly update");
check("Diagnostics lists the unread emails", (await page.locator(".msg").count()) === 3);
check("no stray 'null' text after syncing", !(await page.locator("main, #app").first().innerText()).includes("null"));
const row = page.locator(".msg", { hasText: "Quarterly update" });
await row.locator("text=View email").click();
await page.waitForSelector("pre.original");
check("view email shows the original text", (await page.locator("pre.original").innerText()).trim() === "Numbers are attached.");
await row.locator("text=Close").click();
const news = page.locator(".msg", { hasText: "Weekly news" });
await news.locator("text=Reply").click();
await page.fill("textarea", "Thanks for the update.");
await page.click("text=Send reply");
await page.waitForSelector("text=Reply sent from");
await row.locator("text=Archive").click();
await page.waitForSelector("text=Quarterly update", { state: "detached" });
const hostile = page.locator(".msg", { hasText: "onerror" });
await hostile.locator("text=View email").click();
await page.waitForSelector("pre.original");
check("hostile subject, sender and body ran no code", await page.evaluate(() => window.__pwned === undefined) && (await page.locator(".msg img, pre.original img").count()) === 0);
check("no Content Security Policy violations", csp.length === 0);
await browser.close();
process.exit(failed ? 1 : 0);
